// ─── Shared base element factory ──────────────────────────────────────────────

function el(overrides: Partial<CreativeElement> & Pick<CreativeElement, 'id' | 'type' | 'label' | 'x' | 'y' | 'width' | 'height'>): CreativeElement {
  return {
    visualPriority: 50,
    interactionPriority: 0,
    hidePriority: 50,
    priority: 5,
    minWidth: 100,
    minHeight: 40,
    locked: false,
    preferredZones: ['center'],
    behavior: ['reposition'],
    interactive: false,
    ...overrides,
  };
}

